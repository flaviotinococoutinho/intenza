package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/csv"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strconv"
	"strings"

	"github.com/flaviotinococoutinho/intenza/standards/internal/fold"
	"github.com/flaviotinococoutinho/intenza/standards/internal/succinct"
)

// emitter writes deterministic Go source: one item per line in string blobs so
// that a change in the standard shows up as a one-line diff.
type emitter struct {
	b bytes.Buffer
}

func newEmitter(pkg, source string, digest string) *emitter {
	e := &emitter{}
	e.line("// Code generated by standards/internal/gen from %s; DO NOT EDIT.", source)
	e.line("")
	e.line("package %s", pkg)
	e.line("")
	e.line(`import "github.com/flaviotinococoutinho/intenza/standards/internal/succinct"`)
	e.line("")
	e.line("// sourceSHA256 is the digest of the extract this file was generated from.")
	e.line("const sourceSHA256 = %q", digest)
	e.line("")
	e.line("var _ = succinct.Rank{}")
	e.line("")
	return e
}

func (e *emitter) line(format string, args ...any) {
	fmt.Fprintf(&e.b, format, args...)
	e.b.WriteByte('\n')
}

// blob emits a string constant made of items and the offsets of each item.
func (e *emitter) blob(name string, items []string) {
	e.line("const %s = \"\" +", name)
	for i, it := range items {
		sep := " +"
		if i == len(items)-1 {
			sep = ""
		}
		e.line("\t%s%s", strconv.Quote(it), sep)
	}
	if len(items) == 0 {
		e.line("\t\"\"")
	}
	offs := make([]int, 0, len(items)+1)
	acc := 0
	offs = append(offs, 0)
	for _, it := range items {
		acc += len(it)
		offs = append(offs, acc)
	}
	e.ints(name+"Off", "uint32", offs)
}

// fixed emits a constant whose items all have the same width.
func (e *emitter) fixed(name string, items []string) {
	e.line("const %s = \"\" +", name)
	for i := 0; i < len(items); i += 16 {
		end := min(i+16, len(items))
		sep := " +"
		if end == len(items) {
			sep = ""
		}
		e.line("\t%s%s", strconv.Quote(strings.Join(items[i:end], "")), sep)
	}
}

func (e *emitter) ints(name, typ string, vals []int) {
	e.line("var %s = [%d]%s{", name, len(vals), typ)
	for i := 0; i < len(vals); i += 16 {
		end := min(i+16, len(vals))
		parts := make([]string, 0, end-i)
		for _, v := range vals[i:end] {
			parts = append(parts, strconv.Itoa(v))
		}
		e.line("\t%s,", strings.Join(parts, ", "))
	}
	e.line("}")
	e.line("")
}

func (e *emitter) rank(name string, universe uint32, keys []uint32) {
	r := succinct.Build(universe, keys)
	e.line("var %s = succinct.Rank{Words: %sWords[:], Ranks: %sRanks[:]}", name, name, name)
	e.line("")
	e.line("var %sWords = [%d]uint64{", name, len(r.Words))
	for i := 0; i < len(r.Words); i += 4 {
		end := min(i+4, len(r.Words))
		parts := make([]string, 0, 4)
		for _, w := range r.Words[i:end] {
			parts = append(parts, fmt.Sprintf("0x%016x", w))
		}
		e.line("\t%s,", strings.Join(parts, ", "))
	}
	e.line("}")
	e.line("")
	ranks := make([]int, len(r.Ranks))
	for i, v := range r.Ranks {
		ranks[i] = int(v)
	}
	e.ints(name+"Ranks", "uint16", ranks)
}

// tokens builds the prefix-search index "tokens" over the folded words of each
// record's names.
func (e *emitter) tokens(names [][]string) {
	const name = "tokens"
	type tok struct {
		t   string
		rec int
	}
	var toks []tok
	for rec, ns := range names {
		seen := map[string]bool{}
		for _, n := range ns {
			for w := range strings.FieldsSeq(fold.String(n)) {
				if !seen[w] {
					seen[w] = true
					toks = append(toks, tok{w, rec})
				}
			}
		}
	}
	slices.SortFunc(toks, func(a, b tok) int {
		if c := strings.Compare(a.t, b.t); c != 0 {
			return c
		}
		return a.rec - b.rec
	})
	words := make([]string, len(toks))
	post := make([]int, len(toks))
	for i, t := range toks {
		words[i], post[i] = t.t, t.rec
	}
	e.line("var %s = succinct.Tokens{Blob: %sBlob, Off: %sBlobOff[:], Post: %sPost[:]}", name, name, name, name)
	e.line("")
	e.blob(name+"Blob", words)
	e.ints(name+"Post", "uint16", post)
}

// write formats the source and writes zz_generated.go in the current directory.
func (e *emitter) write() error {
	src, err := format.Source(e.b.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt: %w\n%s", err, e.b.String())
	}
	return os.WriteFile("zz_generated.go", src, 0o600)
}

// readExtract reads a committed CSV extract (comments start with #) and
// returns its rows without the header plus the digest of the file.
func readExtract(path string, fields int) ([][]string, string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, "", err
	}
	sum := sha256.Sum256(raw)
	r := csv.NewReader(bytes.NewReader(raw))
	r.Comment = '#'
	r.FieldsPerRecord = fields
	rows, err := r.ReadAll()
	if err != nil {
		return nil, "", fmt.Errorf("%s: %w", path, err)
	}
	if len(rows) == 0 {
		return nil, "", fmt.Errorf("%s: vazio", path)
	}
	return rows[1:], hex.EncodeToString(sum[:]), nil
}

func atoi(s string) int {
	n, err := strconv.Atoi(strings.TrimSpace(s))
	if err != nil {
		panic(fmt.Sprintf("número inválido %q", s))
	}
	return n
}
